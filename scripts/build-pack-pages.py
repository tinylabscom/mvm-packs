#!/usr/bin/env python3
"""Generate one Markdown page per published pack, plus an index page.

Reads only files already in the tree (index.json, packs/*/*/*/manifest.json
and files/, revocations.toml, docs/publishing-a-pack.md). It never downloads or opens an archive.
Output goes to docs/registry/. Use --check to fail when it is stale.
"""

import argparse
import hashlib
import html
import json
import runpy
import sys
import tomllib
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPTS))
from application_manifest import unique_object, validate_application  # noqa: E402
import pack_details  # noqa: E402
from publisher_identity import (  # noqa: E402
    CURRENT_IDENTITY, FORMER_IDENTITY, PUBLISHER_ISSUER, is_historical_manifest,
)

ROOT = SCRIPTS.parent
OUT = "docs/registry"
HEADER = "<!-- generated by scripts/build-pack-pages.py; do not edit -->\n\n"
IN_ARCHIVE = "recorded in the signed archive; shown after `mvmctl pull`"


class PageError(Exception):
    pass


def load_revocations(root):
    """Reuse the revocation source reader; returns (identities, manifests)."""
    reader = runpy.run_path(str(SCRIPTS / "build-revocations.py"))
    try:
        return reader["read_source"](root / "revocations.toml")
    except (OSError, ValueError, reader["RevocationError"]) as error:
        raise PageError(f"revocations.toml: {error}") from error


def load_manifest(path, expected_sha, reference):
    try:
        raw = path.read_bytes()
    except OSError as error:
        raise PageError(f"{path}: {error}") from error
    if hashlib.sha256(raw).hexdigest() != expected_sha:
        raise PageError(f"{path}: manifest bytes do not match the index pin")
    try:
        manifest = json.loads(raw, object_pairs_hook=unique_object)
    except ValueError as error:
        raise PageError(f"{path}: invalid JSON: {error}") from error
    if not isinstance(manifest, dict) or manifest.get("reference") != reference:
        raise PageError(f"{path}: reference must be {reference}")
    if not isinstance(manifest.get("description"), str):
        raise PageError(f"{path}: description must be a string")
    if manifest.get("schema_version") == 2:
        if manifest.get("kind") != "application":
            raise PageError(f"{path}: schema 2 manifest must be an application")
        try:
            validate_application(manifest.get("application"))
        except ValueError as error:
            raise PageError(f"{path}: {error}") from error
    elif manifest.get("schema_version") != 1 or not isinstance(manifest.get("files"), list):
        raise PageError(f"{path}: unsupported manifest shape")
    return manifest, raw


def read_payload(version_dir, manifest, relative):
    entry = next((item for item in manifest.get("files", [])
                  if isinstance(item, dict) and item.get("path") == relative), None)
    if entry is None:
        return None
    path = version_dir / "files" / relative
    try:
        raw = path.read_bytes()
        if len(raw) != entry["size"] or hashlib.sha256(raw).hexdigest() != entry["sha256"]:
            raise PageError(f"{path}: bytes do not match the signed manifest")
        return raw.decode("utf-8")
    except (OSError, UnicodeError, KeyError, TypeError) as error:
        raise PageError(f"{path}: {error}") from error


def read_policy(version_dir, manifest):
    """Names, hosts and groups only; any other profile field is ignored."""
    policy = {"groups": [], "bindings": [], "allow": []}
    for name in ("profile.toml", "group.toml"):
        relative = f"pack/{name}"
        raw = read_payload(version_dir, manifest, relative)
        if raw is None:
            continue
        try:
            data = tomllib.loads(raw)
            policy["groups"] += list(data.get("groups", {}).get("include", []))
            binds = data.get("overrides", {}).get("secrets", {}).get("bind", [])
            policy["bindings"] += [(b["name"], list(b.get("hosts", []))) for b in binds]
            policy["allow"] += list(data.get("network", {}).get("allow", []))
        except (tomllib.TOMLDecodeError, KeyError, TypeError,
                AttributeError) as error:
            raise PageError(f"{version_dir / 'files' / relative}: {error!r}") from error
    return policy


def signer_identities(reference, raw):
    """Every identity this version can be verified under. Uses the time-free
    historical test (not accepts_former) so a page never changes with the date
    and never under-reports revocation."""
    ids = [CURRENT_IDENTITY]
    if is_historical_manifest(reference, raw):
        ids.append(FORMER_IDENTITY)
    return ids


def human_size(count):
    value = float(count)
    for unit in ("B", "KB", "MB"):
        if value < 1000:
            return f"{value:.0f} {unit}" if unit == "B" else f"{value:.1f} {unit}"
        value /= 1000
    return f"{value:.1f} GB"


def version_row(version, sha, manifest, revoked, has_app):
    cells = [f"`{version}`", f"`{sha}`", "yes" if revoked else "no"]
    if has_app:
        app = manifest.get("application")
        if app:
            bundle = app["bundle"]
            cells += [app["guest_arch"], f"`{bundle['archive_sha256']}`",
                      str(bundle["archive_size"]), f"`{bundle['key_id']}`"]
        else:
            cells += ["—"] * 4
    return "| " + " | ".join(cells) + " |"


def load_details(root, ns, name, version, manifest):
    """Recorded archive details for a version, cross-checked against its descriptor; None if absent."""
    path = root / "pack-details" / ns / name / f"{version}.json"
    if not path.is_file():
        return None
    try:
        if path.stat().st_size > pack_details.MAX_BYTES:
            raise ValueError("file is too large")
        details = pack_details.validate(json.loads(path.read_text(encoding="utf-8"),
                                                   object_pairs_hook=unique_object))
        bundle = manifest["application"]["bundle"]
        if (details["reference"] != f"{ns}/{name}@{version}"
                or details["archive"]["sha256"] != bundle["archive_sha256"]
                or details["archive"]["size"] != bundle["archive_size"]
                or details["archive"]["key_id"] != bundle["key_id"]
                or details["archive"]["arch"] != manifest["application"]["guest_arch"]):
            raise ValueError("does not match the signed descriptor")
    except (OSError, ValueError, KeyError, TypeError) as error:
        raise PageError(f"{path}: {error}") from error
    return details


def render_pack(entry, root, revoked_ids, revoked_shas):
    ns, name = entry["namespace"], entry["name"]
    ref = f"{ns}/{name}"
    loaded = []
    for item in entry["versions"]:
        version, sha = item["version"], item["manifest_sha256"]
        directory = root / "packs" / ns / name / version
        manifest, raw = load_manifest(directory / "manifest.json", sha, f"{ref}@{version}")
        identities = signer_identities(f"{ref}@{version}", raw)
        revoked = sha in revoked_shas or any(i in revoked_ids for i in identities)
        loaded.append((version, sha, manifest, directory, identities, revoked))
    latest_version, _, latest, latest_dir, _, _ = loaded[0]
    is_app = latest.get("kind") == "application"
    has_app = any(m.get("kind") == "application" for _, _, m, _, _, _ in loaded)
    kind = "application" if is_app else "policy"
    arch, size = "—", "—"
    if is_app:
        arch = latest["application"]["guest_arch"]
        size = human_size(latest["application"]["bundle"]["archive_size"])
    summary = {"kind": kind, "arch": arch, "size": size}
    out = [HEADER, f"# `{ref}`\n\n", f"{html.escape(entry['description'])}\n\n",
           "| Reference | Kind | Latest | Architecture | Size | Publisher |\n|---|---|---|---|---|---|\n"
           f"| `{ref}` | {kind} | `{latest_version}` | {arch} | {size} | "
           "tinylabscom/mvm-packs (official) |\n\n"]
    out.append("## Use\n\n```sh\n"
               f"mvmctl pull {ref}\n"
               f"mvmctl pull {ref}@{latest_version}\n")
    if is_app:
        out.append(f"mvmctl run {ref}\n```\n\n")
    else:
        out.append("```\n\nThis pack is a policy and is not runnable: it has no kernel, "
                   "root filesystem or entrypoint.\n\n")
    out.append("## Versions\n\n")
    head = ["Version", "Manifest SHA-256", "Revoked"]
    if has_app:
        head += ["Architecture", "Bundle SHA-256", "Bundle size (bytes)", "Bundle key ID"]
    out.append("| " + " | ".join(head) + " |\n|" + "---|" * len(head) + "\n")
    for version, sha, manifest, _, _, revoked in loaded:
        out.append(version_row(version, sha, manifest, revoked, has_app) + "\n")
    out.append("\n")
    if is_app:
        details = load_details(root, ns, name, latest_version, latest)
        if details is not None:
            out.extend(pack_details.render(details))
        else:
            out.append(f"## Environment\n\nEntrypoint, resources, egress and secret slots: {IN_ARCHIVE}.\n\n"
                       f"Created date: {IN_ARCHIVE}.\n\n")
    else:
        policy = read_policy(latest_dir, latest)
        out.append(f"## Policy declarations (`{latest_version}`)\n\n"
                   "Included groups name other policies; they do not describe every effective permission.\n\n"
                   "| Declaration | Value |\n|---|---|\n")
        for kind, values in (("Included group", policy["groups"]),
                             ("Direct network allow", policy["allow"])):
            for value in values:
                out.append(f"| {kind} | `{value}` |\n")
        if not policy["groups"] and not policy["allow"]:
            out.append("| None declared | — |\n")
        out.append("\n## Secret bindings\n\n"
                   "Binding names and allowed hosts only; a binding is not proof that a secret "
                   "is required, and no secret values are stored here.\n\n"
                   "| Binding | Allowed hosts |\n|---|---|\n")
        for bname, hosts in policy["bindings"]:
            out.append(f"| `{bname}` | {', '.join(f'`{h}`' for h in hosts) or '—'} |\n")
        if not policy["bindings"]:
            out.append("| None declared | — |\n")
        readme = read_payload(latest_dir, latest, "pack/README.md")
        if readme:
            out.append("\n## About this pack\n\n" + html.escape(readme.strip()) + "\n")
        out.append("\n")
    out.append("## Publisher\n\n"
               "Each manifest is signed keyless; `manifest.sigstore.json` binds it to a workflow "
               f"identity (issuer `{PUBLISHER_ISSUER}`). Identities each version can be verified under:\n\n")
    for version, _, _, _, identities, _ in loaded:
        out.append(f"- `{version}`: " + ", ".join(f"`{i}`" for i in identities) + "\n")
    if is_app:
        out.append("\nThe descriptor names a bundle key ID but does not enroll it; the consumer must "
                   "already trust that key.\n")
    return f"{ns}/{name}.md", "".join(out), summary


def card_meta(pack, summaries):
    info = summaries[pack["namespace"], pack["name"]]
    parts = [info["kind"]] + ([info["arch"], info["size"]] if info["kind"] == "application" else [])
    return " · ".join(parts + [f"latest {pack['versions'][0]['version']}"])


def render_index(packs, summaries):
    rows = []
    for pack in packs:
        ref = f"{pack['namespace']}/{pack['name']}"
        rows.append(
            f'<li><a href="{html.escape(ref, quote=True)}.md">'
            f'<strong>{html.escape(ref)}</strong>'
            f'<span>{html.escape(pack["description"])}</span>'
            f'<small>{html.escape(card_meta(pack, summaries))}</small>'
            '</a></li>\n'
        )
    return ("README.md", HEADER + "# Pack registry\n\n"
            "Browse published packs and inspect their declared policies before pulling. "
            "Publication alone is not an official endorsement or proof of safety.\n\n"
            "[Publish a policy pack](publish.md) through a reviewed pull request.\n\n"
            '<ul class="registry-list">\n' + "".join(rows) + '</ul>\n')


def render_publish(root):
    try:
        guide = (root / "docs/publishing-a-pack.md").read_text(encoding="utf-8")
    except (OSError, UnicodeError) as error:
        raise PageError(f"docs/publishing-a-pack.md: {error}") from error
    return "publish.md", HEADER + guide


def generate(root):
    try:
        index = json.loads((root / "index.json").read_text(encoding="utf-8"),
                           object_pairs_hook=unique_object)
        packs = sorted(index["packs"], key=lambda p: (p["namespace"], p["name"]))
    except (OSError, ValueError, KeyError, TypeError) as error:
        raise PageError(f"index.json: {error}") from error
    ids, shas = load_revocations(root)
    ids, shas = set(ids), set(shas)
    rendered = [render_pack(p, root, ids, shas) for p in packs]
    summaries = {(p["namespace"], p["name"]): r[2] for p, r in zip(packs, rendered)}
    pages = [(path, text) for path, text, _ in rendered] + [
        render_index(packs, summaries), render_publish(root)]
    return dict(pages)


def main(argv=None, root=ROOT):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if committed pages are stale")
    args = parser.parse_args(argv)
    try:
        pages = generate(root)
    except PageError as error:
        sys.exit(f"pack pages: {error}")
    out = root / OUT
    if args.check:
        existing = {p.relative_to(out).as_posix() for p in out.rglob("*.md")} if out.is_dir() else set()
        stale = sorted(existing ^ set(pages)) + sorted(
            r for r in set(pages) & existing if (out / r).read_text(encoding="utf-8") != pages[r])
        if stale:
            sys.exit("pack pages: stale (run python3 scripts/build-pack-pages.py): " + ", ".join(stale))
        print(f"pack pages: {len(pages)} page(s) up to date")
        return
    if out.is_dir():
        for old in out.rglob("*.md"):
            old.unlink()
    for rel, text in pages.items():
        (out / rel).parent.mkdir(parents=True, exist_ok=True)
        (out / rel).write_text(text, encoding="utf-8")
    print(f"pack pages: wrote {len(pages)} page(s) to {OUT}")


if __name__ == "__main__":
    main()
