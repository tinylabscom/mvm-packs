#!/usr/bin/env python3
"""Generate one Markdown page per published pack, plus an index page.

Reads only files already in the tree (index.json, packs/*/*/*/manifest.json
and files/, revocations.toml). It never downloads or opens an archive.
Output goes to docs/registry/. Use --check to fail when it is stale.
"""

import argparse
import hashlib
import json
import runpy
import sys
import tomllib
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPTS))
from application_manifest import unique_object, validate_application  # noqa: E402
from publisher_identity import CURRENT_IDENTITY, PUBLISHER_ISSUER  # noqa: E402

ROOT = SCRIPTS.parent
OUT = "docs/registry"
HEADER = "<!-- generated by scripts/build-pack-pages.py; do not edit -->\n\n"
IN_ARCHIVE = "recorded in the signed archive; shown after `mvmctl pull`"


class PageError(Exception):
    pass


def load_revocations(root):
    """Reuse the revocation source reader; returns (identities, manifests)."""
    reader = runpy.run_path(str(SCRIPTS / "build-revocations.py"))
    try:
        return reader["read_source"](root / "revocations.toml")
    except (OSError, ValueError, reader["RevocationError"]) as error:
        raise PageError(f"revocations.toml: {error}") from error


def load_manifest(path, expected_sha, reference):
    try:
        raw = path.read_bytes()
    except OSError as error:
        raise PageError(f"{path}: {error}") from error
    if hashlib.sha256(raw).hexdigest() != expected_sha:
        raise PageError(f"{path}: manifest bytes do not match the index pin")
    try:
        manifest = json.loads(raw, object_pairs_hook=unique_object)
    except ValueError as error:
        raise PageError(f"{path}: invalid JSON: {error}") from error
    if not isinstance(manifest, dict) or manifest.get("reference") != reference:
        raise PageError(f"{path}: reference must be {reference}")
    if not isinstance(manifest.get("description"), str):
        raise PageError(f"{path}: description must be a string")
    if manifest.get("schema_version") == 2:
        if manifest.get("kind") != "application":
            raise PageError(f"{path}: schema 2 manifest must be an application")
        try:
            validate_application(manifest.get("application"))
        except ValueError as error:
            raise PageError(f"{path}: {error}") from error
    elif manifest.get("schema_version") != 1 or not isinstance(manifest.get("files"), list):
        raise PageError(f"{path}: unsupported manifest shape")
    return manifest


def read_policy(version_dir):
    """Names, hosts and groups only; any other profile field is ignored."""
    policy = {"groups": [], "bindings": [], "allow": []}
    for name in ("profile.toml", "group.toml"):
        path = version_dir / "files" / "pack" / name
        if not path.is_file():
            continue
        try:
            data = tomllib.loads(path.read_text(encoding="utf-8"))
            policy["groups"] += list(data.get("groups", {}).get("include", []))
            binds = data.get("overrides", {}).get("secrets", {}).get("bind", [])
            policy["bindings"] += [(b["name"], list(b.get("hosts", []))) for b in binds]
            policy["allow"] += list(data.get("network", {}).get("allow", []))
        except (OSError, UnicodeError, tomllib.TOMLDecodeError, KeyError, TypeError,
                AttributeError) as error:
            raise PageError(f"{path}: {error!r}") from error
    return policy


def version_row(version, sha, manifest, revoked, has_app):
    cells = [f"`{version}`", f"`{sha}`", "yes" if revoked else "no"]
    if has_app:
        app = manifest.get("application")
        if app:
            bundle = app["bundle"]
            cells += [app["guest_arch"], f"`{bundle['archive_sha256']}`",
                      str(bundle["archive_size"]), f"`{bundle['key_id']}`"]
        else:
            cells += ["—"] * 4
    return "| " + " | ".join(cells) + " |"


def render_pack(entry, root, revoked_ids, revoked_shas):
    ns, name = entry["namespace"], entry["name"]
    ref = f"{ns}/{name}"
    loaded = []
    for item in entry["versions"]:
        version, sha = item["version"], item["manifest_sha256"]
        directory = root / "packs" / ns / name / version
        manifest = load_manifest(directory / "manifest.json", sha, f"{ref}@{version}")
        loaded.append((version, sha, manifest, directory))
    latest_version, _, latest, latest_dir = loaded[0]
    is_app = latest.get("kind") == "application"
    has_app = any(m.get("kind") == "application" for _, _, m, _ in loaded)
    out = [HEADER, f"# `{ref}`\n\n", f"{entry['description']}\n\n",
           f"- Reference: `{ref}`\n",
           f"- Kind: {'application' if is_app else 'policy'}\n",
           f"- Latest version: `{latest_version}`\n\n"]
    out.append("## Use\n\n```sh\n"
               f"mvmctl pull {ref}\n"
               f"mvmctl pull {ref}@{latest_version}\n")
    if is_app:
        out.append(f"mvmctl run {ref}\n```\n\n")
    else:
        out.append("```\n\nThis pack is a policy and is not runnable: it has no kernel, "
                   "root filesystem or entrypoint.\n\n")
    out.append("## Versions\n\n")
    head = ["Version", "Manifest SHA-256", "Revoked"]
    if has_app:
        head += ["Architecture", "Bundle SHA-256", "Bundle size (bytes)", "Bundle key ID"]
    out.append("| " + " | ".join(head) + " |\n|" + "---|" * len(head) + "\n")
    for version, sha, manifest, _ in loaded:
        revoked = sha in revoked_shas or CURRENT_IDENTITY in revoked_ids
        out.append(version_row(version, sha, manifest, revoked, has_app) + "\n")
    out.append("\n")
    if is_app:
        out.append(f"## Environment\n\nEntrypoint, resources, egress and secret slots: {IN_ARCHIVE}.\n\n"
                   f"Created date: {IN_ARCHIVE}.\n\n")
    else:
        policy = read_policy(latest_dir)
        out.append(f"## Policy (`{latest_version}`)\n\n")
        out.append("Included groups: " + (", ".join(f"`{g}`" for g in policy["groups"]) or "none") + "\n\n")
        out.append("Secret bindings (names and allowed hosts only; no secret values are stored):\n\n")
        for bname, hosts in policy["bindings"]:
            out.append(f"- `{bname}`: " + ", ".join(f"`{h}`" for h in hosts) + "\n")
        if not policy["bindings"]:
            out.append("- none\n")
        if policy["allow"]:
            out.append("\nNetwork allow list:\n\n" + "".join(f"- `{h}`\n" for h in policy["allow"]))
        out.append("\n")
    out.append("## Publisher\n\n"
               "Each manifest is signed keyless; `manifest.sigstore.json` binds it to workflow identity "
               f"`{CURRENT_IDENTITY}` (issuer `{PUBLISHER_ISSUER}`).\n")
    if is_app:
        out.append("\nThe descriptor names a bundle key ID but does not enroll it; the consumer must "
                   "already trust that key.\n")
    return f"{ns}/{name}.md", "".join(out)


def render_index(packs):
    rows = "".join(
        f"| [`{p['namespace']}/{p['name']}`]({p['namespace']}/{p['name']}.md) | {p['description']} "
        f"| {', '.join('`%s`' % v['version'] for v in p['versions'])} |\n" for p in packs)
    return ("README.md", HEADER + "# Pack registry\n\n| Pack | Description | Versions |\n|---|---|---|\n" + rows)


def generate(root):
    try:
        index = json.loads((root / "index.json").read_text(encoding="utf-8"),
                           object_pairs_hook=unique_object)
        packs = sorted(index["packs"], key=lambda p: (p["namespace"], p["name"]))
    except (OSError, ValueError, KeyError, TypeError) as error:
        raise PageError(f"index.json: {error}") from error
    ids, shas = load_revocations(root)
    ids, shas = set(ids), set(shas)
    pages = [render_pack(p, root, ids, shas) for p in packs] + [render_index(packs)]
    return dict(pages)


def main(argv=None, root=ROOT):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if committed pages are stale")
    args = parser.parse_args(argv)
    try:
        pages = generate(root)
    except PageError as error:
        sys.exit(f"pack pages: {error}")
    out = root / OUT
    if args.check:
        existing = {p.relative_to(out).as_posix() for p in out.rglob("*.md")} if out.is_dir() else set()
        stale = sorted(existing ^ set(pages)) + sorted(
            r for r in set(pages) & existing if (out / r).read_text(encoding="utf-8") != pages[r])
        if stale:
            sys.exit("pack pages: stale (run python3 scripts/build-pack-pages.py): " + ", ".join(stale))
        print(f"pack pages: {len(pages)} page(s) up to date")
        return
    if out.is_dir():
        for old in out.rglob("*.md"):
            old.unlink()
    for rel, text in pages.items():
        (out / rel).parent.mkdir(parents=True, exist_ok=True)
        (out / rel).write_text(text, encoding="utf-8")
    print(f"pack pages: wrote {len(pages)} page(s) to {OUT}")


if __name__ == "__main__":
    main()
