import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';

const source = 'docs/registry';
const destination = 'src/content/docs';

await rm(destination, { recursive: true, force: true });
for (const file of await readdir(source, { recursive: true })) {
  if (!file.endsWith('.md')) continue;
  const input = join(source, file);
  const page = file === 'README.md' ? 'index.md' : file;
  const output = join(destination, page);
  const title = file === 'README.md' ? 'Pack registry'
    : file === 'publish.md' ? 'Publish a policy pack' : file.slice(0, -3);
  let markdown = await readFile(input, 'utf8');
  markdown = markdown
    .replace(/^<!-- generated by scripts\/build-pack-pages\.py; do not edit -->\n\n/, '')
    .replace(/^# [^\n]+\n\n/, '');
  // The generated index links to Markdown files; Starlight routes omit extensions.
  if (file === 'README.md') {
    markdown = markdown.replaceAll(/\]\(([^):]+)\.md\)/g, ']($1/)');
    markdown = markdown.replaceAll(/href="([^"]+)\.md"/g, 'href="$1/"');
  }
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, `---\ntitle: ${JSON.stringify(title)}\n---\n\n${markdown}`);
}
